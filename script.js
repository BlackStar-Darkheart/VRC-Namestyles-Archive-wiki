searchInput.addEventListener("input", displayNamestyles);

sortNameButton.addEventListener("click", () => {
    activeSort = activeSort === "name-asc" ? "name-desc" : "name-asc";
    updateSortButtons();
    displayNamestyles();
});

sortRarityButton.addEventListener("click", () => {
    activeSort = activeSort === "rarity-asc" ? "rarity-desc" : "rarity-asc";
    updateSortButtons();
    displayNamestyles();
});


