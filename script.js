// CREATE A NAMESTYLE CARD
// ==========================================

function getAssetPaths(item) {
    const assetName = (item.id || item.name || "")
        .toLowerCase()
        .replace(/[^a-z0-9]/g, "");
    const coverPath = item.cover && !/\/\.png$/i.test(item.cover)
        ? item.cover
        : assetName ? `images/covers/${assetName}.png` : "";
    const animationPath = item.animation && !/\/\.mp4$/i.test(item.animation)
        ? item.animation
        : assetName ? `animations/${assetName}.mp4` : "";

    return { coverPath, animationPath };
}


function createCard(item) {
    const { coverPath, animationPath } = getAssetPaths(item);
    const card = document.createElement("article");
    card.className = "namestyle-card";

    const previewContainer = document.createElement("div");
    previewContainer.className = "preview-container";

    if (item.previewFit === "contain") {
        previewContainer.classList.add("preview-contain");
    }

    const image = document.createElement("img");

    image.alt = item.name + " preview";
    image.loading = "lazy";
    image.decoding = "async";

    const isVideoAnimation = /\.(mp4|webm|ogv)$/i.test(animationPath);
    const video = isVideoAnimation ? document.createElement("video") : null;

    if (video) {
        video.className = "preview-video";
        video.muted = true;
        video.loop = true;
        video.playsInline = true;
        video.preload = "none";
        video.hidden = true;
        previewContainer.appendChild(video);
    }

    const placeholder = document.createElement("div");
    placeholder.className = "preview-placeholder";
    placeholder.textContent = "No cover image";

    if (coverPath) {
        image.src = coverPath;
        previewContainer.appendChild(image);
    } else {
        previewContainer.appendChild(placeholder);
    }

    let animationActive = false;

    function playAnimation() {
        if (!animationPath || !previewContainer.isConnected) return;

        if (video) {
            if (!video.getAttribute("src")) {
            video.src = animationPath;
            }

            image.hidden = true;
            video.hidden = false;
            animationActive = true;
            video.play().catch(() => {
                video.hidden = true;
                image.hidden = false;
                animationActive = false;
            });
            return;
        }

        if (!image.isConnected) return;

        image.onerror = () => {
            image.onerror = null;

            if (coverPath) {
                image.src = coverPath;
            }
        };

        image.src = animationPath;
        animationActive = true;
    }

    function stopAnimation() {
        if (video) {
            video.pause();
            video.currentTime = 0;
            video.hidden = true;
            image.hidden = false;
            animationActive = false;
            return;
        }

        if (!coverPath || !image.isConnected) return;

        image.onerror = null;
        image.src = coverPath;
        animationActive = false;
    }

    // Desktop: hover to play.

    card.addEventListener("mouseenter", playAnimation);
    card.addEventListener("mouseleave", stopAnimation);

    // Keyboard: focus to play.

    card.addEventListener("focusin", playAnimation);
    card.addEventListener("focusout", stopAnimation);

    // Touchscreens: tap to toggle the animation.

    card.addEventListener("click", () => {
    const isDesktop = window.matchMedia(
        "(hover: hover) and (pointer: fine)"
    ).matches;

    if (isDesktop || !animationPath) return;

    if (animationActive) {
        stopAnimation();
    } else {
        playAnimation();
    }
});

    card.tabIndex = 0;

    // CARD INFORMATION

    const information = document.createElement("div");
    information.className = "card-information";

    const top = document.createElement("div");
    top.className = "card-top";

    const name = document.createElement("h3");
    name.className = "card-name";
    name.textContent = item.name;

    const rarity = document.createElement("span");
    rarity.className = "rarity-label";
    rarity.textContent = item.rarity.toUpperCase();
    rarity.style.color = rarityColors[item.rarity] || "#A0A0A0";

    const description = document.createElement("p");
    description.className = "card-description";
    description.textContent = item.description || "No description available.";

    top.appendChild(name);
    top.appendChild(rarity);

    information.appendChild(top);
    information.appendChild(description);

    card.appendChild(previewContainer);
    card.appendChild(information);

    return card;
}


// ==========================================
// DISPLAY NAMESTYLES
// ==========================================

function displayNamestyles() {
    gallery.innerHTML = "";

    const searchTerm = searchInput.value.toLowerCase().trim();

    const filteredNamestyles = namestyles.filter(item => {

        const matchesRarity =
            activeFilter === "All" || item.rarity === activeFilter;

        const matchesSearch =
            item.name.toLowerCase().includes(searchTerm) ||
            (item.description || "").toLowerCase().includes(searchTerm);

        return matchesRarity && matchesSearch;
    });

    const sortedNamestyles = filteredNamestyles.sort((first, second) => {
        const firstName = (first.name || "").trim();
        const secondName = (second.name || "").trim();

        if (!firstName && secondName) return 1;
        if (firstName && !secondName) return -1;

        if (activeSort === "name-asc" || activeSort === "name-desc") {
            const nameOrder = firstName.localeCompare(secondName, undefined, {
                sensitivity: "base"
            });
            return activeSort === "name-asc" ? nameOrder : -nameOrder;
        }

        const firstRank = rarityOrder.indexOf(first.rarity);
        const secondRank = rarityOrder.indexOf(second.rarity);
        const firstUnknown = firstRank === -1;
        const secondUnknown = secondRank === -1;

        if (firstUnknown !== secondUnknown) return firstUnknown ? 1 : -1;

        const rarityDifference = firstRank - secondRank;
        if (rarityDifference !== 0) {
            return activeSort === "rarity-asc"
                ? rarityDifference
                : -rarityDifference;
        }

        return firstName.localeCompare(secondName, undefined, {
            sensitivity: "base"
        });
    });

    sortedNamestyles.forEach(item => {
        gallery.appendChild(createCard(item));
    });

    resultsCount.textContent =
        `${filteredNamestyles.length} results`;

    emptyMessage.hidden = filteredNamestyles.length !== 0;
}


function updateSortButtons() {
    const nameAscending = activeSort === "name-asc";
    const nameDescending = activeSort === "name-desc";
    const rarityAscending = activeSort === "rarity-asc";
    const rarityDescending = activeSort === "rarity-desc";

    sortNameButton.textContent = nameDescending ? "Z-A" : "A-Z";
    sortNameButton.classList.toggle("active", nameAscending || nameDescending);
    sortNameButton.setAttribute("aria-pressed", nameAscending || nameDescending);
    sortNameButton.title = nameDescending ? "Sort names Z to A" : "Sort names A to Z";

    const rarityArrow = String.fromCharCode(rarityDescending ? 8595 : 8593);
    sortRarityButton.textContent = `Rarity ${rarityArrow}`;
    sortRarityButton.classList.toggle("active", rarityAscending || rarityDescending);
    sortRarityButton.setAttribute("aria-pressed", rarityAscending || rarityDescending);
    sortRarityButton.title = rarityDescending
        ? "Sort rarity from Legendary to Common"
        : "Sort rarity from Common to Legendary";
}


